// Generates lib/landing/land-dots.ts: an evenly spaced dot grid over the world's
// land, for the landing globe. Run once with `node scripts/gen-land-dots.mjs`.
// Data: Natural Earth (public domain) via the world-atlas package (land-50m).

import { readFileSync, writeFileSync } from "node:fs";
import { geoContains } from "d3-geo";
import { feature } from "topojson-client";

const STEP_DEG = 1.1;
const topo = JSON.parse(readFileSync(new URL("../node_modules/world-atlas/land-50m.json", import.meta.url)));
const land = feature(topo, topo.objects.land);

const points = [];
for (let lat = -84; lat <= 84; lat += STEP_DEG) {
  // Wider longitude steps toward the poles keep the dots evenly spaced on the sphere.
  const lngStep = STEP_DEG / Math.max(0.2, Math.cos((lat * Math.PI) / 180));
  for (let lng = -180; lng < 180; lng += lngStep) {
    if (geoContains(land, [lng, lat])) points.push(Math.round(lat * 10), Math.round(lng * 10));
  }
}

const out = `// Generated by scripts/gen-land-dots.mjs from Natural Earth land (public domain,
// via world-atlas). ${points.length / 2} dots, ${STEP_DEG}° apart. Pairs of lat*10, lng*10.
export const LAND_DOTS = new Int16Array([${points.join(",")}]);
`;
writeFileSync(new URL("../lib/landing/land-dots.ts", import.meta.url), out);
console.log(`${points.length / 2} land dots`);
